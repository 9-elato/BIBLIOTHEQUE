import {writeFileSync} from 'node:fs'

// Compare procedural swatches under front light, side light and at follow-camera distance.
const profiles={
 ghost:{count:50,targets:[.032,.018,.026],ranges:[[60,108],[.018,.072],[.04,.18]]},
 fox:{count:120,targets:[.056,.026,.045],ranges:[[42,93],[.025,.105],[.07,.29]]},
}
const fract=n=>n-Math.floor(n)
const sample=(u,v,frequency)=>Math.sin(u*frequency+Math.sin(v*frequency*.61))*Math.cos(v*frequency*1.31)
function score({frequency,contrast,roughness},targets){
 let variation=0,sideLight=0,distance=0,alias=0
 for(let i=0;i<256;i++){
  const u=fract(i*.61803399),v=fract(i*.41421356)
  const grain=sample(u,v,frequency),next=sample(u+.009,v+.004,frequency)
  variation+=Math.abs(grain)*contrast
  sideLight+=Math.abs(grain-next)*roughness
  distance+=Math.abs(grain+next)*contrast*.5
  alias+=Math.abs(grain-next)*contrast
 }
 const averages=[variation/256,sideLight/256,distance/256]
 return averages.reduce((sum,value,i)=>sum+((value-targets[i])/targets[i])**2,0)+alias/256
}

const result={}
for(const [character,{count,targets,ranges}] of Object.entries(profiles)){
 const candidates=Array.from({length:count},(_,i)=>{
  const parameters=ranges.map(([min,max],axis)=>Number((min+(max-min)*fract((i+1)*[.61803399,.41421356,.73205081][axis])).toFixed(5)))
  const [frequency,contrast,roughness]=parameters
  const detail={frequency,contrast,roughness}
  return {round:i+1,...detail,score:Number(score(detail,targets).toFixed(6))}
 })
 const best=candidates.reduce((a,b)=>a.score<=b.score?a:b)
 result[character]={evaluated:count,...best}
 console.log(character,JSON.stringify(result[character]))
}
const source='// Generated by scripts/refine-avatar-detail.mjs.\nexport const avatarDetailProfiles = '+JSON.stringify(result,null,2)+'\n'
writeFileSync(new URL('../src/avatarDetailProfiles.js',import.meta.url),source)
